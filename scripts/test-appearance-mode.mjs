import { _electron as electron, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'photocalendar-mode-'));
const env = { ...process.env, PHOTO_CALENDAR_DATA_DIR: directory, PHOTO_CALENDAR_TEST: '1' };
delete env.ELECTRON_RUN_AS_NODE; delete env.VITE_DEV_SERVER_URL;
let app, page;
const failures = [];
async function launch() {
  app = await electron.launch(process.argv.includes('--packaged') ? { executablePath: path.join(root, 'release/win-unpacked/Photo Calendar.exe'), args: [], env } : { args: [root], env });
  page = await app.firstWindow(); page.on('pageerror', e => failures.push(e.message));
  // Playwright otherwise emulates light mode and masks nativeTheme updates.
  await page.emulateMedia({ colorScheme: null });
  await expect(page.locator('.calendar')).toBeVisible();
}
const settings = () => page.evaluate(async () => (await window.calendar.load()).settings);
const openSettings = async () => { await page.getByRole('button', { name: '위젯 설정', exact: true }).click(); await page.getByRole('tab', { name: '테마', exact: true }).click(); };
try {
  await launch();
  assert.equal((await settings()).colorMode, 'system');
  assert.equal((await settings()).softFocus, true);
  const widget = page.locator('.widget');
  await app.evaluate(({ nativeTheme }) => { nativeTheme.themeSource = 'light'; });
  await expect(widget).toHaveClass(/mode-light/);
  await expect(widget).toHaveClass(/theme-polaroid/);
  const date = page.locator('.is-today .date-number');
  await expect(date).toHaveCSS('filter', 'blur(0.45px)');
  await expect(page.locator('.month-title')).toHaveCSS('filter', 'blur(0.45px)');
  assert.equal(await page.locator('.is-today').evaluate(cell => getComputedStyle(cell, '::after').filter), 'blur(0.45px)');
  const fonts = await page.evaluate(async () => { await Promise.all(['Gowun Dodum','Cormorant Garamond','Caveat'].map(name => document.fonts.load(`16px "${name}"`))); return [...document.fonts].filter(font => font.status === 'loaded').map(font => font.family.replaceAll('"','')); });
  for (const name of ['Gowun Dodum','Cormorant Garamond','Caveat']) assert.ok(fonts.includes(name), `${name} loads from the bundle`);
  await page.screenshot({ path: path.join(root, 'test-results/refined-polaroid-light.png') });
  await app.evaluate(({ nativeTheme }) => { nativeTheme.themeSource = 'dark'; });
  await expect(widget).toHaveClass(/mode-dark/);
  await expect(widget).toHaveClass(/theme-polaroid/);
  await page.screenshot({ path: path.join(root, 'test-results/refined-polaroid-dark.png') });
  const before = await date.boundingBox();
  await openSettings();
  const blur = page.getByRole('switch', { name: '달력 글자·선 블러', exact: true });
  await expect(blur).toBeChecked(); await blur.click();
  await expect(date).toHaveCSS('filter', 'none');
  await expect(page.locator('.month-title')).toHaveCSS('filter', 'none');
  assert.equal(await page.locator('.is-today').evaluate(cell => getComputedStyle(cell, '::after').filter), 'none');
  await page.getByRole('combobox', { name: '화면 밝기 모드', exact: true }).selectOption('dark');
  await expect.poll(async () => (await settings()).colorMode).toBe('dark');
  await app.evaluate(({ nativeTheme }) => { nativeTheme.themeSource = 'light'; });
  await expect(widget).toHaveClass(/mode-dark/);
  await page.getByRole('button', { name: '설정 닫기', exact: true }).click();
  assert.deepEqual(await date.boundingBox(), before, 'Blur toggle never moves the dates');
  await page.locator('.is-today .day-date').click();
  await expect(page.locator('.widget')).toHaveClass(/editor-open\b/);
  await expect(page.locator('.day-editor')).toHaveCSS('filter', 'none');
  await expect(page.locator('.memo-editor')).toHaveCSS('filter', 'none');
  await expect(page.locator('.day-editor')).toHaveCSS('background-color', 'rgb(41, 41, 41)');
  await page.keyboard.press('Escape');
  await expect(widget).toHaveClass(/editor-closed\b/);
  await openSettings();
  await page.getByRole('combobox', { name: '화면 밝기 모드', exact: true }).selectOption('system');
  await page.getByRole('button', { name: '아날로그 테마 적용', exact: true }).click();
  await page.getByRole('button', { name: '설정 닫기', exact: true }).click();
  await app.evaluate(({ nativeTheme }) => { nativeTheme.themeSource = 'dark'; });
  await expect(widget).toHaveClass(/mode-dark/);
  await page.screenshot({ path: path.join(root, 'test-results/refined-analog-dark.png') });
  await app.close(); app = null;
  await launch();
  assert.equal((await settings()).softFocus, false);
  assert.equal((await settings()).colorMode, 'system');
  const native = await app.evaluate(({ nativeTheme }) => ({ source: nativeTheme.themeSource, dark: nativeTheme.shouldUseDarkColors }));
  assert.equal(native.source, 'system');
  await expect(page.locator('.widget')).toHaveClass(new RegExp(`mode-${native.dark ? 'dark' : 'light'}`));
  await openSettings();
  await page.getByRole('switch', { name: '달력 글자·선 블러', exact: true }).click();
  await expect.poll(async () => (await settings()).softFocus).toBe(true);
  await page.getByRole('tab', { name: '화면', exact: true }).click();
  await page.getByRole('combobox', { name: '글꼴', exact: true }).selectOption('Gowun Dodum');
  const size = page.getByRole('spinbutton', { name: '전체 글자 크기', exact: true });
  await size.fill('26'); await size.press('Tab');
  await expect(page.locator('.themed-month small')).toHaveCSS('font-family', /^"Gowun Dodum"/);
  await expect(page.locator('.themed-month small')).toHaveCSS('font-size', '34px');
  assert.deepEqual(failures, []);
  console.log('PASS: bundled fonts, system brightness updates, preserved theme design, manual override, calendar-only blur toggle and restart persistence.');
} finally {
  if (app) await app.close().catch(() => {});
  if (path.dirname(directory) === os.tmpdir() && path.basename(directory).startsWith('photocalendar-mode-')) fs.rmSync(directory, { recursive: true, force: true, maxRetries: 10, retryDelay: 100 });
}
