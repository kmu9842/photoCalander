import { _electron as electron, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import sharp from 'sharp';
import { createRequire } from 'node:module';
const root = path.resolve(import.meta.dirname, '..');
const { CalendarStore } = createRequire(import.meta.url)('../electron/store.cjs');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'photocalendar-themes-'));
const store = new CalendarStore(directory);
store.saveSettings({ ...store.data.settings, showHolidays: false });
const env = { ...process.env, PHOTO_CALENDAR_DATA_DIR: directory, PHOTO_CALENDAR_TEST: '1' };
delete env.ELECTRON_RUN_AS_NODE; delete env.VITE_DEV_SERVER_URL;
let app, page;
const failures = [];
async function launch() {
  app = await electron.launch(process.argv.includes('--packaged') ? { executablePath: path.join(root, 'release/win-unpacked/Photo Calendar.exe'), args: [], env } : { args: [root], env });
  page = await app.firstWindow();
  page.on('pageerror', e => failures.push(e.message));
  await expect(page.locator('.calendar')).toBeVisible();
}
const data = () => page.evaluate(() => window.calendar.load());
const openSettings = async () => { await page.getByRole('button', { name: '위젯 설정', exact: true }).click(); await page.getByRole('tab', { name: '테마', exact: true }).click(); };
try {
  await launch();
  await expect(page.locator('.widget')).toHaveClass(/theme-polaroid/);
  const assertMonochrome = async () => {
    const colors = await page.evaluate(() => {
      const widget = document.querySelector('.widget'), style = getComputedStyle(widget);
      return ['--panel', '--text', '--accent', '--line'].map(key => style.getPropertyValue(key).trim()).concat(Array.from(document.querySelectorAll('.weekdays>div, .day-cell .date-number, .holiday-name'), el => getComputedStyle(el).color));
    });
    for (const color of colors) {
      const channels = color.startsWith('#') ? [1,3,5].map(i => parseInt(color.slice(i,i+2),16)) : color.match(/[\d.]+/g).slice(0,3).map(Number);
      assert.ok(channels.every(value => value === channels[0]), `Theme chrome must be monochrome: ${color}`);
    }
  };
  await assertMonochrome();
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setBounds({ x: 100, y: 80, width: 1200, height: 850 }));
  const month = (await page.locator('.is-today').getAttribute('data-date')).slice(0,7), date = month + '-16';
  const imagePath = path.join(directory, 'photo.png');
  await sharp({ create: { width: 640, height: 480, channels: 3, background: '#719689' } }).composite([{ input: await sharp({ create: { width: 300, height: 220, channels: 3, background: '#d7b588' } }).png().toBuffer(), top: 150, left: 100 }]).png().toFile(imagePath);
  await page.evaluate(async ({ date, month, imagePath }) => {
    const photos = await window.calendar.importPhotos([{ name: '숲의 기억', path: imagePath }, { name: '가을 산책', path: imagePath }]);
    for (const day of [3,8,16,21,27]) await window.calendar.saveDay(`${month}-${String(day).padStart(2,'0')}`, { text: day === 16 ? '일상을 기록해요\n오후 산책' : '작은 기억', strikes: [], color: 'none', photos: day === 16 ? photos : [photos[0]], photoSize: day === 8 ? 'small' : 'medium' });
  }, { date, month, imagePath });
  await page.reload();
  await openSettings();
  await expect(page.getByRole('tab')).toHaveCount(5);
  await page.getByRole('button', { name: '폴라로이드 테마 적용', exact: true }).click();
  await expect.poll(async () => (await data()).settings.theme).toBe('polaroid');
  await page.getByRole('tab', { name: '화면', exact: true }).click();
  await expect(page.getByRole('slider', { name: '배경 불투명도', exact: true })).toHaveValue('96');
  await page.getByRole('button', { name: '설정 닫기', exact: true }).click();
  const cell = page.locator(`[data-date="${date}"]`);
  await expect(cell.locator('.frame-polaroid')).toHaveCount(2);
  const artwork = await cell.locator('.frame-art').first().evaluate(el => getComputedStyle(el).backgroundImage);
  assert.match(artwork, /polaroid-frame\.jpg/);
  await expect(cell.locator('.frame-art').first()).toHaveCSS('filter', 'grayscale(1)');
  await expect(cell.locator('.photo-image').first()).toHaveCSS('filter', 'none');
  await assertMonochrome();
  const assets = await page.evaluate(async () => Promise.all(['analog-paper','polaroid-frame','stamp-frame-v2'].map(name => new Promise(resolve => { const image = new Image(); image.onload = () => resolve({ name, width: image.naturalWidth }); image.onerror = () => resolve({ name, width: 0 }); image.src = new URL(`./assets/${name}.jpg`, location.href).href; }))));
  assert.ok(assets.every(asset => asset.width > 1000), 'Actual generated artwork loads from the application');
  assert.ok(await cell.locator('.cell-notes').evaluate(el => el.scrollHeight <= el.clientHeight), 'Two-line notes remain fully visible with medium frames');
  fs.mkdirSync(path.join(root, 'test-results'), { recursive: true });
  await page.screenshot({ path: path.join(root, 'test-results/theme-polaroid.png') });
  await cell.locator('.day-date').click();
  await expect(page.locator('.widget')).toHaveClass(/editor-open\b/);
  await page.getByRole('button', { name: '사진 틀 · 위치 · 기울기', exact: true }).click();
  const arrangement = page.getByRole('region', { name: '사진 프레임과 배치' });
  await arrangement.getByRole('button', { name: '우표', exact: true }).click();
  await expect.poll(async () => (await data()).days[date].photos[0].frame).toBe('stamp');
  assert.equal((await data()).days[date].photos[1].frame, undefined, 'Per-photo frame does not change another photo');
  const noteBefore = await cell.locator('.note-text').boundingBox();
  const x = page.getByRole('slider', { name: '사진 가로 위치', exact: true });
  await x.focus(); await x.press('Home');
  await expect.poll(async () => (await data()).days[date].photos[0].placement?.x).toBe(0);
  const y = page.getByRole('slider', { name: '사진 세로 위치', exact: true });
  await y.focus(); await y.press('Home');
  const rotation = page.getByRole('slider', { name: '사진 기울기', exact: true });
  await rotation.focus(); await rotation.press('End');
  await expect.poll(async () => (await data()).days[date].photos[0].placement?.rotation).toBe(30);
  const target = arrangement.locator('.placement-photo.selected');
  await target.scrollIntoViewIfNeeded();
  const targetBox = await target.boundingBox();
  await page.mouse.move(targetBox.x + targetBox.width * .65, targetBox.y + targetBox.height * .75);
  await page.mouse.down(); await page.mouse.move(targetBox.x + targetBox.width * .65 + 25, targetBox.y + targetBox.height * .75 + 20, { steps: 6 }); await page.mouse.up();
  await expect.poll(async () => (await data()).days[date].photos[0].placement?.x).toBeGreaterThan(0);
  const noteAfter = await cell.locator('.note-text').boundingBox();
  assert.deepEqual(noteAfter, noteBefore, 'Moving/rotating photos never reflows the notes');
  const actual = await cell.locator('.positioned-photo').first().boundingBox(), outer = await cell.boundingBox();
  assert.ok(actual.x >= outer.x && actual.y >= outer.y && actual.x + actual.width <= outer.x + outer.width && actual.y + actual.height <= outer.y + outer.height, 'Rotated photo stays inside the date');
  await page.screenshot({ path: path.join(root, 'test-results/photo-frame-editor.png') });
  await page.getByRole('group', { name: '날짜 사진 크기' }).getByRole('button', { name: '대', exact: true }).click();
  await expect(rotation).toBeDisabled();
  const full = await cell.locator('.cell-photos').boundingBox();
  assert.ok(Math.abs(full.width - outer.width) <= 1 && Math.abs(full.height - outer.height) <= 1, 'Large framed photos fill the date');
  await x.focus(); await x.press('End');
  await expect.poll(async () => (await data()).days[date].photos[0].placement.x).toBe(100);
  await expect(cell.locator('.photo-image').first()).toHaveCSS('object-fit', 'cover');
  const cropPosition = await cell.locator('.photo-image').first().evaluate(el => getComputedStyle(el).objectPosition);
  assert.ok(cropPosition.startsWith('100%'), 'Large-photo placement moves the image crop');
  await page.getByRole('group', { name: '날짜 사진 크기' }).getByRole('button', { name: '소', exact: true }).click();
  await page.keyboard.press('Escape');
  await expect(page.locator('.widget')).toHaveClass(/editor-closed\b/);
  const thumb = await cell.locator('.cell-photo').boundingBox();
  await page.mouse.move(thumb.x + thumb.width / 2, thumb.y + thumb.height / 2);
  await expect(page.getByRole('tooltip')).toBeVisible();
  const preview = await page.getByRole('tooltip').boundingBox();
  assert.ok(preview.width > outer.width && preview.height > outer.height, 'Small framed thumbnail still expands beyond the date on hover');
  await page.keyboard.press('Escape');
  await openSettings();
  await page.getByRole('button', { name: '아날로그 테마 적용', exact: true }).click();
  await expect.poll(async () => (await data()).settings.theme).toBe('analog');
  await assertMonochrome();
  await page.getByRole('button', { name: '설정 닫기', exact: true }).click();
  await page.screenshot({ path: path.join(root, 'test-results/theme-analog.png') });
  await openSettings();
  await page.getByRole('button', { name: '새 테마 만들기', exact: true }).click();
  await page.getByRole('textbox', { name: '테마 이름', exact: true }).fill('나의 아날로그');
  await page.getByLabel('테마 배경 색상', { exact: true }).fill('#dfe8dc');
  await page.getByLabel('테마 글자 색상', { exact: true }).fill('#29352a');
  await page.getByRole('combobox', { name: '테마 밝기 모드', exact: true }).selectOption('light');
  await page.getByRole('combobox', { name: '테마 질감', exact: true }).selectOption('paper');
  await page.getByRole('combobox', { name: '테마 기본 사진 틀', exact: true }).selectOption('polaroid');
  await page.getByRole('button', { name: '저장하고 적용', exact: true }).click();
  await expect.poll(async () => (await data()).settings.theme).toBe('custom');
  const saved = (await data()).settings;
  assert.equal(saved.customThemes.length, 1);
  assert.equal(saved.customThemes[0].background, '#dfe8dc');
  await app.close(); app = null;
  await launch();
  assert.deepEqual((await data()).settings, saved, 'Saved user theme survives restart');
  assert.equal((await data()).days[date].photos[0].frame, 'stamp', 'Explicit frame survives a theme change and restart');
  assert.ok((await data()).days[date].photos[0].placement.x > 0);
  await openSettings();
  await page.getByRole('button', { name: '나의 아날로그 테마 편집', exact: true }).click();
  await page.getByRole('textbox', { name: '테마 이름', exact: true }).fill('두 번째 테마');
  await page.getByRole('button', { name: '새 테마로 저장', exact: true }).click();
  await expect.poll(async () => (await data()).settings.customThemes.length).toBe(2);
  await page.getByRole('button', { name: '두 번째 테마 테마 삭제', exact: true }).click();
  await expect.poll(async () => (await data()).settings.theme).toBe('polaroid');
  await expect.poll(async () => (await data()).settings.customThemes.length).toBe(1);
  assert.deepEqual(failures, []);
  console.log('PASS: generated frame assets, reference themes, per-photo frame/drag/rotation, stable notes, small hover preview, custom theme editing/copy/delete and restart persistence.');
} catch (error) {
  if (page) await page.screenshot({ path: path.join(root, 'test-results/themes-failure.png') }).catch(() => {});
  throw error;
} finally {
  if (app) await app.close().catch(() => {});
  if (path.dirname(directory) === os.tmpdir() && path.basename(directory).startsWith('photocalendar-themes-')) fs.rmSync(directory, { recursive: true, force: true, maxRetries: 10, retryDelay: 100 });
}
