import { _electron as electron, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
const root = path.resolve(import.meta.dirname, '..');
const { CalendarStore } = createRequire(import.meta.url)('../electron/store.cjs');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'photocalendar-formatting-'));
const store = new CalendarStore(directory);
store.saveSettings({ ...store.data.settings, showHolidays: false });
const now = new Date(), date = `${now.getFullYear()}-${String(now.getMonth()+1).padStart(2,'0')}-${String(now.getDate()).padStart(2,'0')}`;
store.saveDay(date, { text: '첫 줄 중요\n둘째 줄 완료\n셋째 줄', strikes: [], textSizes: [{ from: 4, to: 6, size: 26 }], fontSize: 18, color: 'none', photos: [] });
const env = { ...process.env, PHOTO_CALENDAR_DATA_DIR: directory, PHOTO_CALENDAR_TEST: '1' };
delete env.ELECTRON_RUN_AS_NODE; delete env.VITE_DEV_SERVER_URL;
let app, page;
const failures = [];
const launch = async () => {
  app = await electron.launch(process.argv.includes('--packaged') ? { executablePath: path.join(root, 'release/win-unpacked/Photo Calendar.exe'), args: [], env } : { args: [root], env });
  page = await app.firstWindow(); page.on('pageerror', error => failures.push(error.message));
  await expect(page.locator('.calendar')).toBeVisible();
};
const cell = () => page.locator(`[data-date="${date}"]`);
const saved = () => page.evaluate(async date => (await window.calendar.load()).days[date], date);
try {
  await launch();
  await cell().locator('.day-date').click();
  const memo = page.getByRole('textbox', { name: '메모 내용' });
  await expect(page.locator('.day-editor [role=spinbutton], .day-editor input[type=number], .strike-button')).toHaveCount(0);
  await expect(page.getByRole('switch', { name: '날짜 사진 블러' })).toHaveCount(0);
  await expect(memo).toHaveCSS('font-size', '18px');
  await expect(memo.getByText('중요', { exact: true })).toHaveCSS('font-size', '26px');
  await expect(memo.getByRole('checkbox')).toHaveCount(3);
  await memo.press('Control+Home');
  await memo.getByRole('checkbox', { name: '2번째 줄 완료', exact: true }).click();
  await expect(memo.locator('s')).toHaveText('둘째 줄 완료');
  await expect(memo.getByRole('checkbox', { name: '2번째 줄 완료', exact: true })).toBeChecked();
  await expect(cell().locator('s')).toHaveText('둘째 줄 완료');
  await memo.press('Control+z'); await expect(memo.locator('s')).toHaveCount(0);
  await memo.press('Control+y'); await expect(memo.locator('s')).toHaveText('둘째 줄 완료');
  await memo.getByRole('checkbox', { name: '2번째 줄 완료', exact: true }).click();
  await expect(memo.locator('s')).toHaveCount(0);
  await memo.press('Control+End'); await memo.press('Control+5');
  await memo.press('Enter'); await page.keyboard.insertText('새 줄');
  await expect(memo.locator('s')).toHaveText('셋째 줄');
  await memo.press('Control+5'); await memo.press('Shift+Enter'); await page.keyboard.insertText('다음 줄');
  await expect(memo.getByRole('checkbox')).toHaveCount(5);
  await memo.getByRole('checkbox', { name: '5번째 줄 완료', exact: true }).click();
  await expect(memo.locator('s')).toHaveText(['셋째 줄', '새 줄', '다음 줄']);
  await memo.getByRole('checkbox', { name: '5번째 줄 완료', exact: true }).click();
  await expect(memo.locator('s')).toHaveText(['셋째 줄', '새 줄']);
  await expect.poll(async () => (await saved()).text).toBe('첫 줄 중요\n둘째 줄 완료\n셋째 줄\n새 줄\n다음 줄');
  await expect.poll(async () => (await saved()).textSizes).toEqual([{ from: 4, to: 6, size: 26 }]);
  fs.mkdirSync(path.join(root, 'test-results'), { recursive: true });
  await page.screenshot({ path: path.join(root, 'test-results/memo-checkboxes.png') });
  await page.keyboard.press('Escape'); await expect(page.locator('.day-editor')).toHaveCount(0);
  await app.close(); app = null;
  await launch(); await cell().locator('.day-date').click();
  await expect(page.getByRole('textbox', { name: '메모 내용' }).locator('s')).toHaveText(['셋째 줄', '새 줄']);
  await expect(page.getByRole('checkbox', { name: '3번째 줄 완료', exact: true })).toBeChecked();
  await expect(page.getByRole('checkbox', { name: '5번째 줄 완료', exact: true })).not.toBeChecked();
  assert.deepEqual(failures, []);
  console.log('PASS: per-line completion checkboxes, undo/redo, Ctrl+5, Enter/Shift+Enter, simplified editor, preserved existing font sizes and restart persistence.');
} finally {
  if (app) await app.close().catch(() => {});
  if (path.dirname(directory) === os.tmpdir() && path.basename(directory).startsWith('photocalendar-formatting-')) fs.rmSync(directory, { recursive: true, force: true, maxRetries: 10, retryDelay: 100 });
}
